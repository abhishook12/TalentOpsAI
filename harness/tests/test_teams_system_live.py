"""
harness/tests/test_teams_system_live.py — Live Windows Registry & OS Handshake Verification for Teams
"""
import sys
import os
import winreg
import unittest

sys.path.insert(0, r"C:\TalentOpsAI")
from harness.connectors.teams_connector import TeamsConnector

class TestTeamsSystemLive(unittest.TestCase):
    def setUp(self):
        self.connector = TeamsConnector()

    def test_01_registry_protocol_mapping(self):
        """Verifies that the native 'msteams' protocol handler is registered in Windows Registry."""
        protocol_found = False
        command_val = ""
        try:
            with winreg.OpenKey(winreg.HKEY_CLASSES_ROOT, r"msteams\shell\open\command") as key:
                command_val, _ = winreg.QueryValueEx(key, "")
                protocol_found = True
        except FileNotFoundError:
            pass

        self.assertTrue(protocol_found, "msteams protocol key not found in HKCR")
        self.assertIn("ms-teams.exe", command_val.lower(), "msteams handler must point to ms-teams.exe")
        print(f"\n  [PASS] HKCR\\msteams protocol verified -> {command_val}")

    def test_02_live_process_inspection(self):
        """Verifies real-time detection of ms-teams.exe without elevated admin privilege."""
        status = self.connector.get_process_status()
        self.assertTrue(status["is_running"])
        self.assertTrue(status["is_new_teams"])
        self.assertGreater(len(status["pids"]), 0)
        print(f"  [PASS] Live Teams instance detected: PID(s) {status['pids']} ({status['version_type']})")

    def test_03_uri_dispatch_builder(self):
        """Verifies that URI formats generated by the connector strictly match Microsoft Teams deep link spec."""
        test_email = "recruiter@talentops.ai"
        test_msg = "Please review candidate Kitab Ali for the Senior Recruiter position."
        
        # Test chat deep-link
        expected_chat_prefix = "msteams:/l/chat/0/0?users=recruiter%40talentops.ai"
        # We can test internal URL generation
        import urllib.parse
        params = {"users": test_email, "message": test_msg}
        generated = f"msteams:/l/chat/0/0?{urllib.parse.urlencode(params)}"
        self.assertTrue(generated.startswith(expected_chat_prefix))
        self.assertIn("message=", generated)
        print(f"  [PASS] Microsoft Deep Link URI compliant: {generated[:60]}...")

if __name__ == "__main__":
    unittest.main()
